// oxdump/analysis/xref.h — частичная деобфускация имён по строковым ссылкам.
//
// ЧТО ЭТО. Метаданные этой сборки прогнаны обфускатором: у большинства методов
// оригинальные имена стёрты и заменены мусором вида `hlA`, `nqW`. Полностью их
// не восстановить, но часть методов ССЫЛАЕТСЯ на строковые литералы в своём
// коде (лог-сообщения, имена событий, пути ресурсов). Если метод `hlA` первым
// делом грузит строку "OpenFurnace", это довольно надёжная ПОДСКАЗКА к его
// назначению. Мы её вычисляем и кладём комментарием рядом с методом — это не
// переименование, а HINT-колонка в dump.cs / offsets.h.
//
// КАК. Для каждого обфусцированного метода с известным RVA (только основная
// сборка Assembly-CSharp) дизассемблируем начало тела и ищем на ARM64
// последовательности `ADRP+ADD` (адрес строки прямо в rodata) и `ADRP+LDR`
// (указатель на строку через слот данных). Первый осмысленный строковый литерал
// и есть подсказка. Работает только для методов с валидным RVA и стоит секунд,
// поэтому включается отдельным флагом `--xref-names`.
//
// ЧЕСТНОЕ ОГРАНИЧЕНИЕ. IL2CPP почти никогда не встраивает литералы игры прямо в
// код: они идут через таблицу string-literal / MetadataUsage. На сильно
// обфусцированных сборках (как эта) связь метод→литерал в метаданных вырезана, и
// прямых ссылок в коде остаются единицы. Пасс написан корректно и без ложных
// подсказок: лучше 10 надёжных, чем 74k выдуманных. На менее агрессивно
// обфусцированной цели выход будет выше — эвристика та же.
#pragma once
#include "oxdump/common.h"
#include "oxdump/binary/image.h"
#include "oxdump/model/model.h"
#include <string>
#include <vector>
#include <unordered_map>

namespace oxdump::analysis {

// Подсказка к одному методу: где он в модели и на какой литерал ссылается.
struct MethodHint {
    u32 type_idx = 0;           // индекс родительского typedef
    u32 method_idx = 0;         // порядковый индекс метода внутри типа
    std::string first_string;   // первый осмысленный строковый литерал, ≤ 64 симв.
};

// Сканирует код обфусцированных методов основной сборки и собирает подсказки.
//
// m       — модель (даёт таблицы, RVA методов и доступ к бинарнику через bin()).
// bin     — сырые байты бинарника (для чтения кода по file-offset).
// img     — разобранный образ (ELF/Mach-O/PE) для va→fo и чтения указателей.
//           ТЗ называет этот параметр elf::Elf64&; в текущем дереве конвейер
//           переведён на общий binary::BinaryImage, поэтому берём базовый тип —
//           используются только ptr()/va2fo()/is_valid_va(), общие для всех
//           форматов.
// budget_per_method — потолок работы на метод в БАЙТАХ кода (64 КБ по
//           умолчанию); фактически ограничивает число разбираемых инструкций.
//
// Возвращает по одной записи на каждый метод, для которого нашлась осмысленная
// строка. Методы без подсказки в результат не попадают.
std::vector<MethodHint>
build_hints(model::Model& m, ByteView bin, binary::BinaryImage& img,
            std::size_t budget_per_method = 65536);

// Ключ (type_idx, method_idx) -> строка. Генераторам удобнее словарь, чем
// линейный список: dump.cs/offsets.h обращаются к подсказке по месту метода.
// Строит из результата build_hints.
std::unordered_map<u64, std::string>
hint_index(const std::vector<MethodHint>& hints);

// Упаковка (type_idx, method_idx) в один ключ для hint_index.
inline u64 hint_key(u32 type_idx, u32 method_idx) noexcept {
    return (static_cast<u64>(type_idx) << 32) | method_idx;
}

// Похоже ли имя на обфусцированное (короткий смешанный регистр: `hlA`, `nqW`).
// Вынесено в заголовок: тем же критерием пользуются генераторы, чтобы решить,
// показывать ли подсказку (у неискажённых имён она не нужна).
bool looks_obfuscated(const std::string& name) noexcept;

// ── реестр активных подсказок ────────────────────────────────────────────
//
// Интерфейс output/generators.h трогать нельзя (это общий контракт), а
// прокинуть подсказки в dump.cs/offsets.h надо. Решение — маленький реестр на
// уровне модуля analysis: main.cpp наполняет его при `--xref-names` ДО вызова
// генераторов, а генераторы спрашивают lookup_hint() по месту метода. Без флага
// реестр пуст, lookup_hint() всегда возвращает пусто — поведение и вывод
// побайтово прежние. Одна генерация на процесс, поток один: глобального
// состояния здесь достаточно, оно не усложняет модель владения.

// Устанавливает активный набор подсказок (перемещением). Зовётся из main.cpp.
void set_active_hints(std::vector<MethodHint> hints);

// Подсказка для метода (type_idx, method_idx) или пустая строка, если её нет
// или реестр не заполнен. Дёшево: один поиск в хеш-таблице.
const std::string& lookup_hint(u32 type_idx, u32 method_idx) noexcept;

// Есть ли вообще активные подсказки (для раннего выхода в генераторах).
bool have_hints() noexcept;

}  // namespace oxdump::analysis
